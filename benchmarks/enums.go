package main

import (
	"fmt"
	"math/rand/v2"
	"strconv"
	"strings"
)

// EnumType is one enum type in a definition file.
type EnumType struct {
	File       string // enum definition file this type lives in
	Name       string
	Items      []EnumItem
	Bitflags   bool
	Underlying string
}

// EnumItem is one member of an enum type.
type EnumItem struct {
	Name  string
	Value int64
}

// value renders an enum value. Non-strict fields may also carry a raw number,
// which is how designers often write flags they have not named yet; strict
// fields accept item names only.
func (e *EnumType) value(r *rand.Rand, strict bool) string {
	if e.Bitflags {
		n := 1 + r.IntN(2)
		picked := pickDistinct(r, len(e.Items), n)
		names := make([]string, 0, n)
		for _, i := range picked {
			names = append(names, e.Items[i].Name)
		}
		return strings.Join(names, "+")
	}
	it := e.Items[r.IntN(len(e.Items))]
	if !strict && r.IntN(5) == 0 {
		return strconv.FormatInt(it.Value, 10)
	}
	return it.Name
}

// pickDistinct returns n distinct indices below limit, or as many as exist.
func pickDistinct(r *rand.Rand, limit, n int) []int {
	if n > limit {
		n = limit
	}
	perm := r.Perm(limit)
	return perm[:n]
}

var enumTypeNouns = []string{
	"itemKind", "weaponClass", "armorSlot", "damageType", "rarity", "faction",
	"questState", "shopKind", "buffKind", "targetKind", "moveMode", "aiState",
	"seasonKind", "currency", "battleRole", "skillKind", "petKind", "mountKind",
	"gemKind", "runeKind", "titleKind", "achieveKind", "mailKind", "guildRank",
	"arenaTier", "dungeonKind", "eventKind", "unlockKind", "growthKind", "lootKind",
	"biomeKind", "weatherKind", "traitKind", "elementKind", "stanceKind",
}

var enumItemNouns = []string{
	"none", "alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf",
	"hotel", "india", "juliet", "kilo", "lima", "mike", "november", "oscar",
	"papa", "quebec", "romeo", "sierra", "tango", "uniform", "victor", "whiskey",
}

var enumFlagNouns = []string{
	"none", "fire", "frost", "shock", "toxin", "holy", "shadow", "arcane",
	"bleed", "stun", "root", "silence",
}

// buildEnums plans the enum corpus: `files` definition files holding `total`
// enum types between them, two of which are bitflag enums.
func (c *Corpus) buildEnums(files, total int) {
	r := c.rng
	names := r.Perm(len(enumTypeNouns))
	for i := range total {
		name := enumTypeNouns[names[i%len(names)]]
		if i >= len(enumTypeNouns) {
			name += strconv.Itoa(i)
		}
		e := &EnumType{
			File:       fmt.Sprintf("bench%d.enum.yaml", i%files+1),
			Name:       name,
			Underlying: "int32",
		}
		// The last two types are bitflag enums, which back the bitflags fields.
		if i >= total-2 {
			e.Bitflags = true
			e.Underlying = "uint32"
			n := 6 + r.IntN(5)
			for j := range n {
				item := EnumItem{Name: enumFlagNouns[j%len(enumFlagNouns)]}
				if j > 0 {
					item.Value = 1 << (j - 1)
				}
				e.Items = append(e.Items, item)
			}
		} else {
			n := 6 + r.IntN(19)
			for j := range n {
				e.Items = append(e.Items, EnumItem{
					Name:  enumItemNouns[j%len(enumItemNouns)] + suffixFor(j),
					Value: int64(j),
				})
			}
		}
		c.enums = append(c.enums, e)
		if e.Bitflags {
			c.bitflagEnums = append(c.bitflagEnums, e)
		} else {
			c.plainEnums = append(c.plainEnums, e)
		}
	}
	for i := range files {
		c.enumFiles = append(c.enumFiles, fmt.Sprintf("bench%d.enum.yaml", i+1))
	}
}

// suffixFor keeps item names unique once the noun pool wraps around.
func suffixFor(j int) string {
	if j < len(enumItemNouns) {
		return ""
	}
	return strconv.Itoa(j / len(enumItemNouns))
}

// renderEnumFile writes one enum definition file in YAML. It is written by
// hand rather than through a YAML marshaller so that item order is stable and
// the file reads the way a human would write it.
func (c *Corpus) renderEnumFile(file string) string {
	var b strings.Builder
	b.WriteString("# Generated by magebench. Do not edit.\n\n")
	b.WriteString("__desc__: Enum definitions for the Archmage benchmark corpus.\n\n")
	b.WriteString("__namespace__:\n")
	b.WriteString("    go: \"magebench/output/enums\"\n")
	b.WriteString("    cs: \"Bench.Enums\"\n")
	for _, e := range c.enums {
		if e.File != file {
			continue
		}
		_, _ = fmt.Fprintf(&b, "\n%s:\n", e.Name)
		_, _ = fmt.Fprintf(&b, "    __desc__: %s enumeration.\n", e.Name)
		b.WriteString("    __options__:\n")
		_, _ = fmt.Fprintf(&b, "        underlyingType: %q\n", e.Underlying)
		if e.Bitflags {
			b.WriteString("        bitflags: true\n")
		}
		for _, it := range e.Items {
			_, _ = fmt.Fprintf(&b, "    %s: %d\n", it.Name, it.Value)
		}
	}
	return b.String()
}
